"""Freeze an independently validated fresh lab, outside model control."""
from pathlib import Path
import json, time
from ssh_lab import command
from snapshot_control import qmp, restore

ROOT=Path(__file__).resolve().parent

def main():
    matrix=json.loads((ROOT/'matrix-validation.json').read_text())
    expected={(c['id'],v) for c in json.loads((ROOT/'cases.json').read_text()) for v in range(3)}
    assert len(matrix)==240 and {(r['case'],r['variant']) for r in matrix}==expected
    assert all(r['initial_fault_verified'] for r in matrix),'Verify all240 initial faults first'
    snapshots=qmp('info snapshots')
    if 'ops-main-v5' in snapshots['result']:raise RuntimeError('Existing snapshot retained; use a new lab')
    script='set -eu\ntest "$(hostname)" = ops-lab\ntest -f /var/lib/ops-harness/fixture-bootstrap-complete\ntest ! -e /var/lib/ops-harness/main-snapshot-marker\npython3 /opt/ops-lab/fixture-reset.py N01 0\ndate -u -s @'+str(int(time.time()))+''' >/dev/null
# Only the disposable guest; QEMU restrict=on separately denies external egress.
ip route del default 2>/dev/null || true
printf '%s\n' ops-main-v5 > /var/lib/ops-harness/main-snapshot-marker
curl -fsS --max-time 3 http://127.0.0.1:18880/health
sync
'''
    p=command(script,timeout=90)
    if p.returncode or 'OPS_LAB_V0_OK' not in p.stdout:raise RuntimeError('Fresh baseline is not healthy')
    result=qmp('savevm');verified=restore()
    (ROOT/'generated-snapshot-validation.json').write_text(json.dumps({'creation':result,'restore':verified},indent=2)+'\n')
    manifest=json.loads((ROOT/'main-fixture-manifest.json').read_text())
    generated=json.loads((ROOT/'lab-build/generated-image-manifest.json').read_text())
    for field,name in [('root_qcow2_sha256','golden.qcow2'),('data_qcow2_sha256','data-golden.qcow2'),('seed_iso_sha256','seed.iso')]:manifest[field]=generated[name]['sha256']
    manifest['image_distribution']='Fresh private images/keys generated by reproducer; differ from published as-tested hashes.'
    (ROOT/'main-fixture-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print('Fresh snapshot independently restored and healthy; new protocol records generated image hashes.')

if __name__=='__main__':main()
